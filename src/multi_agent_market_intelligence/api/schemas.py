"""Pydantic request and response schemas for REST API endpoints."""

from datetime import datetime, timezone
from typing import Any

from pydantic import BaseModel, Field, field_validator

from multi_agent_market_intelligence.state.models import (
    AgentExecutionRecord,
    PortfolioSnapshot,
    RiskDecision,
    TradingSignal,
)


class HealthResponse(BaseModel):
    """Service health check and telemetry status response model."""

    status: str = Field(default="healthy", description="Operational health status.")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC probe verification timestamp.",
    )
    service: str = Field(
        default="Multi-Agent Market Intelligence API",
        description="Application service identifier.",
    )
    version: str = Field(default="0.1.0", description="Deployed application version.")


class AnalysisRequest(BaseModel):
    """Request payload initiating autonomous multi-agent analysis pipeline."""

    symbols: list[str] = Field(
        min_length=1,
        description="Target ticker symbols to analyze (e.g. ['AAPL', 'MSFT']).",
    )
    initial_cash: float = Field(
        default=100_000.0,
        gt=0.0,
        description="Initial liquid cash capital allocation for the analysis run.",
    )
    correlation_id: str | None = Field(
        default=None,
        description="Optional unique tracking identifier for distributed audit tracing.",
    )

    @field_validator("symbols")
    @classmethod
    def validate_symbols(cls, v: list[str]) -> list[str]:
        """Ensure symbols list contains non-empty uppercase ticker strings."""
        cleaned = [s.strip().upper() for s in v if s.strip()]
        if not cleaned:
            raise ValueError("symbols list must contain at least one valid ticker symbol.")
        return cleaned


class AnalysisResponse(BaseModel):
    """Completed multi-agent intelligence analysis workflow response."""

    status: str = Field(
        default="SUCCESS",
        description="Workflow completion status.",
    )
    correlation_id: str = Field(
        description="Distributed tracking correlation identifier.",
    )
    symbols: list[str] = Field(
        description="Target asset symbols evaluated in this run.",
    )
    signals: list[TradingSignal] = Field(
        default_factory=list,
        description="Trading signals generated by the Trading Analyst node.",
    )
    decisions: list[RiskDecision] = Field(
        default_factory=list,
        description="Risk decisions evaluated by the Risk & Portfolio Manager node.",
    )
    portfolio: PortfolioSnapshot = Field(
        description="Updated portfolio asset snapshot post-execution.",
    )
    records: list[AgentExecutionRecord] = Field(
        default_factory=list,
        description="Audit execution logs and latency metrics for each DAG node.",
    )
    execution_time_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Total end-to-end DAG execution latency in milliseconds.",
    )


class ErrorResponse(BaseModel):
    """Standardized error envelope returned for API exceptions and validation failures."""

    error: str = Field(description="Error classification type or exception name.")
    detail: str | list[Any] = Field(
        description="Descriptive error explanation or field validation errors."
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC failure timestamp.",
    )
