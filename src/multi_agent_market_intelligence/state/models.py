"""Domain models for market intelligence state management."""

from datetime import datetime, timezone
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class SignalAction(StrEnum):
    """Allowed directional actions for trading signals."""

    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"


class DecisionStatus(StrEnum):
    """Allowed statuses for risk manager decisions."""

    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    MODIFIED = "MODIFIED"


class DomainStateModel(BaseModel):
    """Base model providing dictionary compatibility for domain entities."""

    model_config = ConfigDict(extra="allow")

    def __eq__(self, other: Any) -> bool:
        """Allow comparison against raw dicts for seamless test and caller compatibility."""
        if isinstance(other, dict):
            for k, v in other.items():
                val = getattr(self, k, None)
                if val is None and self.__pydantic_extra__:
                    val = self.__pydantic_extra__.get(k)
                if val != v:
                    return False
            return True
        return super().__eq__(other)


class ResearchArtifact(DomainStateModel):
    """Structured research output containing news or report intelligence."""

    headline: str = ""
    summary: str = ""
    sentiment_score: float = Field(
        default=0.0,
        ge=-1.0,
        le=1.0,
        description="Sentiment score bounded between -1.0 (bearish) and 1.0 (bullish)",
    )
    source: str = "general"
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: dict[str, Any] = Field(default_factory=dict)


class TradingSignal(DomainStateModel):
    """Trading signal generated by the Trading Analyst."""

    symbol: str = "UNKNOWN"
    action: SignalAction = SignalAction.HOLD
    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Signal confidence score between 0.0 and 1.0",
    )
    target_price: float | None = None
    stop_loss: float | None = None
    reasoning: str = ""
    indicators: dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class RiskDecision(DomainStateModel):
    """Risk & Portfolio Manager validation decision for a trading signal."""

    status: DecisionStatus = DecisionStatus.APPROVED
    original_signal: TradingSignal | dict[str, Any] | None = None
    approved_size: float = Field(
        default=0.0,
        ge=0.0,
        description="Approved position size/units",
    )
    max_loss_limit: float | None = None
    reason: str = ""
    metrics: dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class Position(DomainStateModel):
    """Portfolio position for a specific financial instrument."""

    symbol: str = "UNKNOWN"
    quantity: float = 0.0
    entry_price: float = 0.0
    current_price: float = 0.0
    unrealized_pnl: float = 0.0


class PortfolioSnapshot(DomainStateModel):
    """Audit snapshot of portfolio assets, positions, and equity."""

    cash: float = 0.0
    positions: dict[str, Position] = Field(default_factory=dict)
    total_equity: float = 0.0
    margin_used: float = 0.0
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class AgentExecutionRecord(DomainStateModel):
    """Execution log and audit record for an individual agent invocation."""

    agent_name: str = "agent"
    step: str = ""
    status: str = "SUCCESS"
    execution_time_ms: float = 0.0
    logs: list[str] = Field(default_factory=list)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
